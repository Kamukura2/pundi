import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..", "..");
const read = file => readFileSync(resolve(root, file), "utf8");
const app = read("app.js");
const sync = read("src/sync/sync-manager.js");
const html = read("index.html");
const vercel = read("vercel.json");
const sw = read("public/sw.js");
const styles = read("styles.css");

assert.match(sync, /resetPasswordForEmail\(email, \{ redirectTo \}\)/);
assert.match(sync, /window\.location\.origin\}\/auth\/reset-password/);
assert.match(vercel, /\/auth\/reset-password/);
assert.match(sw, /pundi-shell-v8\.5\.0/);
assert.match(app, /onAuthStateChange\(\(event,session\)=>/);
assert.match(app, /event!=="PASSWORD_RECOVERY"/);
assert.match(app, /exchangeCodeForSession\(callbackCode\)/);
assert.match(app, /recoveryEventPromise/);
assert.match(app, /setAuthMode\("initializing"\)/);
assert.match(app, /Verifying reset link/);
assert.match(app, /history\.replaceState\(null,"",RECOVERY_ROUTE\)/);
assert.match(app, /recoverySubscription/);
assert.match(app, /setAuthMessage\("success","Password updated successfully\. Sign in with your new password\."\)/);
assert.match(app, /signOut\(\{reload:false\}\)/);
assert.match(app, /setAuthMessage\("success",flash\)/);
assert.match(app, /authError\.className="auth-message error"/);
assert.match(app, /authError\.className=`auth-message \$\{kind\}`/);
assert.match(app, /setAuthMessage\("error",authErrorMessage\(error,authMode\)\)/);
assert.match(app, /authConfirmField\.hidden=!\(signUp\|\|recovery\)/);
assert.match(app, /authConfirm\.required=signUp\|\|recovery/);
assert.match(app, /authPassword\.hidden=forgot\|\|expired\|\|initializing/);
assert.match(app, /authRecoveryCancel\.hidden=!recovery/);
assert.match(sync, /await supabase\.auth\.signOut\(\)/);
assert.match(sync, /const \{ data:\{ session \} \}\s*=\s*await supabase\.auth\.getSession\(\)/);
assert.match(sync, /Sign-out did not clear the active session/);
assert.match(app, /recoveryMode=false;recoveryEventSeen=false;recoveryUserId=null;location\.assign\("\/"\)/);
assert.match(app, /recoveryMode=true/);
assert.match(app, /if\(recoveryMode\) return/);
assert.match(app, /location\.pathname===RECOVERY_ROUTE/);
const updateIndex = app.indexOf('changePassword(authPassword.value,{recovery:true');
const signOutIndex = app.indexOf('await syncManager.signOut({reload:false})', updateIndex);
const clearIndex = app.indexOf('sessionStorage.removeItem(RECOVERY_PENDING_KEY)', signOutIndex);
const routeIndex = app.indexOf('location.assign("/")', clearIndex);
assert.ok(updateIndex >= 0 && signOutIndex > updateIndex && clearIndex > signOutIndex && routeIndex > clearIndex, "Recovery completion must update, sign out, clear state, then route");
assert.doesNotMatch(app.slice(updateIndex, routeIndex), /syncManager\.connect|showSignedIn/, "Recovery completion must not bootstrap the dashboard");
assert.match(styles, /\.auth-message\.success\{color:[^}]*--|\.auth-message\.success\{color:#34c88b/);
assert.match(app, /user\?\.id===recoveryUserId/);
assert.match(app, /changePassword\(authPassword\.value,\{recovery:true,expectedUserId:recoveryUserId\}\)/);
assert.match(app, /Password updated successfully\./);
assert.match(app, /pundi-auth-flash/);
assert.match(app, /signOut\(\{reload:false\}\)/);
assert.match(app, /setAuthMode\("expired"\)/);
assert.match(app, /This password reset link is invalid or has expired\./);
assert.match(app, /authMode==="expired"/);
assert.match(app, /Passwords do not match/);
assert.match(app, /Network error/);
assert.match(app, /authRecoveryCancel/);
assert.match(html, /id="authRecoveryCancel"/);
console.log("Password recovery contract PASS: dedicated route, recovery precedence, session binding, safe reset completion, expired-link state, and error categories");
